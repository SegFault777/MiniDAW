#!/usr/bin/env python3
"""Generates src/ui/FontData.cpp: anti-aliased ASCII glyph atlases (Liberation Sans, SIL OFL) used by the
Qt-free UI toolkit when no operating-system text renderer is available (tests, screenshots)."""
import sys
from PIL import ImageFont
D = "/usr/share/fonts/truetype/liberation/"
FACES = [("Regular11", D + "LiberationSans-Regular.ttf", 11), ("Regular13", D + "LiberationSans-Regular.ttf", 13),
         ("Bold11", D + "LiberationSans-Bold.ttf", 11), ("Bold13", D + "LiberationSans-Bold.ttf", 13)]
out = ['// Generated by tools/gen_font.py - Liberation Sans (SIL Open Font License 1.1). Do not edit.',
       '#include "FontData.h"', '', 'namespace ui {', '']
for name, path, px in FACES:
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    data, glyphs = [], []
    for c in range(32, 127):
        ch = chr(c)
        adv = f.getlength(ch)
        mask = f.getmask(ch, mode="L")
        w, h = mask.size
        bb = f.getbbox(ch, anchor="ls")   # relative to the baseline / left origin
        off = len(data)
        data.extend(list(mask)) if w and h else None
        glyphs.append((round(adv * 64), bb[0], bb[1], w, h, off))
    out.append(f'static const unsigned char k{name}Data[] = {{')
    for i in range(0, len(data), 24):
        out.append('    ' + ','.join(str(v) for v in data[i:i + 24]) + ',')
    out.append('0};')
    out.append(f'static const Glyph k{name}Glyphs[95] = {{')
    for g in glyphs:
        out.append('    {%d,%d,%d,%d,%d,%d},' % g)
    out.append('};')
    out.append(f'const GlyphFace g{name} = {{{px}, {asc}, {asc + desc}, k{name}Glyphs, k{name}Data}};')
    out.append('')
out.append('}  // namespace ui')
open(sys.argv[1] if len(sys.argv) > 1 else "src/ui/FontData.cpp", "w").write("\n".join(out) + "\n")
