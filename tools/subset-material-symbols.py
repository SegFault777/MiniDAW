#!/usr/bin/env python3
"""Builds src/vulkan/IconFontData.cpp: the Material Symbols icons that MiniDAW uses, built into the program.

The full fonts (Google, Apache-2.0, about 10 MB each) are not stored in the repository. This script takes them once, pins the variable
font to its default instance (FILL 0, GRAD 0, opsz 24, wght 400), keeps only the glyphs that src/vulkan/IconFont.cpp asks for (every name
of candidates()), and writes the result as C++ byte arrays. Run it again after adding an icon:

    python3 tools/subset-material-symbols.py <folder with MaterialSymbols{Outlined,Rounded,Sharp}*.ttf>

Needs fontTools (pip install fonttools). Not used at build time.
"""
import io, os, re, sys, glob
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STYLES = ["Outlined", "Rounded", "Sharp"]

def wanted_names():
    src = open(os.path.join(ROOT, "src/vulkan/IconFont.cpp"), encoding="utf-8").read()
    table = re.search(r"static const std::vector<std::vector<const char\*>> table = \{(.*?)\};", src, re.S).group(1)
    names = []
    for n in re.findall(r'"([a-z0-9_.]+)"', table):
        if n not in names:
            names.append(n)
    return names

def build(path, names):
    font = TTFont(path)
    have = set(font.getGlyphOrder())
    keep = [n for n in names if n in have]
    opts = subset.Options()
    opts.glyph_names = True            # the post table keeps the icon names: that is how MiniDAW finds a glyph
    opts.layout_features = []
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [1, 2, 3, 4, 5, 6, 13, 14]
    opts.drop_tables += ["STAT", "meta", "prep", "gasp"]
    s = subset.Subsetter(opts)
    s.populate(glyphs=keep)
    s.subset(font)
    font = instancer.instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400})
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue(), keep

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names = wanted_names()
    out = ['// MiniDAW - a lightweight Logic Pro-inspired digital audio workstation',
           '// SPDX-License-Identifier: GPL-3.0-or-later',
           '//',
           '// GENERATED by tools/subset-material-symbols.py - do not edit. The icons of Material Symbols that MiniDAW uses, default instance',
           '// (FILL 0, GRAD 0, opsz 24, wght 400) of the Outlined, Rounded and Sharp fonts. Material Symbols are Copyright Google LLC,',
           '// Apache License 2.0 (see THIRD-PARTY.md and licenses/MaterialSymbols-LICENSE.txt). These files are subsets of the original fonts.',
           '#include "IconFontData.h"', '', 'namespace vkui {', '']
    infos = []
    for style in STYLES:
        files = sorted(glob.glob(os.path.join(sys.argv[1], f"MaterialSymbols{style}*.ttf")))
        if not files:
            sys.exit(f"no MaterialSymbols{style}*.ttf in {sys.argv[1]}")
        data, keep = build(files[0], names)
        missing = [n for n in names if n not in keep]
        print(f"{style}: {len(keep)} icons, {len(data)} bytes; not in the font: {missing}")
        out.append(f"static const unsigned char k{style}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
        infos.append((style, len(data)))
    out.append("const EmbeddedIconFont& embeddedIconFont(int style) {")
    out.append("    static const EmbeddedIconFont none{nullptr, 0};")
    for i, (style, n) in enumerate(infos):
        out.append(f"    static const EmbeddedIconFont f{i}{{k{style}, {n}}};")
    out.append("    switch (style) {")
    for i in range(len(infos)):
        out.append(f"    case {i + 1}: return f{i};")
    out.append("    default: return none;")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("}  // namespace vkui")
    open(os.path.join(ROOT, "src/vulkan/IconFontData.cpp"), "w", encoding="utf-8").write("\n".join(out) + "\n")

main()
